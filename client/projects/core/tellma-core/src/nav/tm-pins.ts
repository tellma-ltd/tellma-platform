import { tmPreferenceKey, type TmPreferenceKey } from '../state/prefs/tm-preference-key';

// The pins model's types and keys (spec 0027 §8.2): the user's pinned pages
// and one-level folders, stored per tenant in the curated preference
// `nav.pinned`, and the pinned bar's switch. A pin is a tenant-relative URL,
// so it fits a live tenant and its sandbox alike. A value of the wrong shape
// reads as the fallback; the pinned bar, in the shell, judges the items one
// by one and applies the bar's rules to them.

/** A pinned page. */
export interface TmPin {
  /** The pin's id: 8 lower-case base32 characters, generated by the client. */
  readonly id: string;
  /** The tenant-relative URL, without a leading slash: `centers?f.CenterType=in:Service`; at most 512 characters. */
  readonly url: string;
  /** The page's title when it was pinned, in that language; at most 80 characters. */
  readonly title: string;
  /** The user's own name for the pin, at most 40 characters; it wins over every derived label. */
  readonly label?: string;
}

/** A named folder of pins, one level deep. */
export interface TmPinFolder {
  /** The folder's id, of the pins' form. */
  readonly id: string;
  /** The folder's name: 1 to 40 characters, unique per user ignoring case. */
  readonly folder: string;
  /** The folder's pins, in order. */
  readonly items: readonly TmPin[];
}

/** One item of the pinned bar: a pin or a folder. */
export type TmPinItem = TmPin | TmPinFolder;

/** The stored value of `nav.pinned`. */
export interface TmPinsDoc {
  /** The value's format version. */
  readonly v: 1;
  /** The top-level items, in the bar's order. */
  readonly items: readonly TmPinItem[];
}

/** Whether a value is a non-null object. */
function isObject(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null;
}

/**
 * Whether a stored value has the shape of `nav.pinned`: format version 1 and
 * a list of items. Items are judged one by one when the bar reads them.
 *
 * @param value - The stored value.
 * @returns Whether it is a pins document.
 */
function isPinsDoc(value: unknown): value is TmPinsDoc {
  return isObject(value) && value['v'] === 1 && Array.isArray(value['items']);
}

/** The user's pins in the routed tenant: `nav.pinned`, curated, with no pins as its fallback. */
export const tmPinsKey: TmPreferenceKey<TmPinsDoc> = /* @__PURE__ */ tmPreferenceKey<TmPinsDoc>(
  'nav.pinned',
  'curated',
  { v: 1, items: [] },
  isPinsDoc,
);

/** Whether the pinned bar shows: `nav.pinnedBarVisible`, curated, shown by default. */
export const tmPinnedBarVisibleKey: TmPreferenceKey<boolean> = /* @__PURE__ */ tmPreferenceKey<boolean>(
  'nav.pinnedBarVisible',
  'curated',
  true,
  (value): value is boolean => typeof value === 'boolean',
);
