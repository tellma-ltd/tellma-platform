using System.Globalization;

namespace Tellma.Queryex.Testing.Semantics
{
    /// <summary>One Gregorian date and the Ethiopian date ICU gives it.</summary>
    /// <param name="Gregorian">The Gregorian date.</param>
    /// <param name="Ethiopian">The Ethiopian date.</param>
    public sealed record EthiopicVector(DateOnly Gregorian, CalendarDate Ethiopian);

    /// <summary>
    ///     The Ethiopian dates of ICU's <c>ethiopic</c> calendar, as the client's date formatting
    ///     reads them, checked in so the suites hold the engine and the reference reading to the
    ///     same outside source.
    /// </summary>
    /// <remarks>
    ///     Every boundary day of every Ethiopian year that overlaps 1900 to 2100 — the first day of a year,
    ///     of a quarter and of Pagume, the last days of the third quarter, of Nehase and of Pagume
    ///     — and the pinned conformance dates, some of which reach centuries further. Generated by
    ///     a script beside the engine's other tooling, never edited by hand.
    /// </remarks>
    public static class EthiopicVectors
    {
        /// <summary>The name the vector file is embedded under.</summary>
        private const string ResourceName = "Tellma.Queryex.Testing.EthiopicVectors.csv";

        /// <summary>Every vector, in date order.</summary>
        public static IReadOnlyList<EthiopicVector> All { get; } = Load();

        /// <summary>Reads the embedded file.</summary>
        /// <returns>The vectors.</returns>
        /// <exception cref="InvalidOperationException">The file is missing or a line is malformed.</exception>
        private static List<EthiopicVector> Load()
        {
            using Stream stream = typeof(EthiopicVectors).Assembly.GetManifestResourceStream(ResourceName)
                ?? throw new InvalidOperationException("The Ethiopian vector file is not embedded.");
            using StreamReader reader = new(stream);

            List<EthiopicVector> vectors = [];

            // The first line names the columns.
            _ = reader.ReadLine();
            while (reader.ReadLine() is string line)
            {
                if (line.Length == 0)
                {
                    continue;
                }

                string[] fields = line.Split(',');
                if (fields.Length != 4)
                {
                    throw new InvalidOperationException("A malformed Ethiopian vector: '" + line + "'.");
                }

                vectors.Add(new EthiopicVector(
                    DateOnly.ParseExact(fields[0], "yyyy-MM-dd", CultureInfo.InvariantCulture),
                    new CalendarDate(
                        int.Parse(fields[1], CultureInfo.InvariantCulture),
                        int.Parse(fields[2], CultureInfo.InvariantCulture),
                        int.Parse(fields[3], CultureInfo.InvariantCulture))));
            }

            return vectors;
        }
    }
}
