/**
 * Writes the `Region_<code>` names of Tellma.Core's shared resources: one entry per region of the
 * language catalogue, in every language Core ships strings for, with the region's CLDR display name
 * in that language. Run from anywhere: `node eng/region-names/generate-region-names.mjs`, or with
 * `--check` to fail (exit code 1) when the files differ from what the script would write.
 *
 * The names come from the ICU data of the running Node.js, whose CLDR release must be the one the
 * platform pins, so the output is the same on every machine and operating system.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The CLDR release the names come from: the release the pinned culture data is generated from. */
const PINNED_CLDR = '48.0';

/** The repository root, two folders above this script. */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Core's resources folder: `Strings.resx` (English, neutral) and its satellites. */
const RESOURCES = join(ROOT, 'src', 'core', 'Tellma.Core', 'Resources');

/** The pinned culture data, whose sections name every language and region pair of the catalogue. */
const CULTURE_DATA = join(ROOT, 'src', 'core', 'Tellma.Core', 'Localization', 'CultureData.txt');

/** The comment that opens the generated block. */
const BLOCK_START = `  <!-- Region_ names: generated by eng/region-names from CLDR ${PINNED_CLDR}; regenerate them, never edit by hand -->\n`;

/** The comment that closes the generated block. */
const BLOCK_END = '  <!-- End of Region_ names -->\n';

/** Matches a generated block, so a rerun replaces it. */
const BLOCK_PATTERN = /  <!-- Region_ names: .*?<!-- End of Region_ names -->\n/s;

/** Matches a `Region_` entry outside the block, which a rerun also replaces. */
const ENTRY_PATTERN = /  <data name="Region_[A-Z]{2}"[^>]*>.*?<\/data>\n/gs;

/** Bidirectional controls, which server text never carries. */
const BIDI_CONTROLS = /[؜‎‏‪-‮⁦-⁩]/gu;

// --- The pinned CLDR release, or nothing is written ---
if (process.versions.cldr !== PINNED_CLDR) {
  console.error(
    `This Node.js carries CLDR ${process.versions.cldr ?? 'unknown'} (ICU ${process.versions.icu ?? 'unknown'}), `
      + `but the region names are pinned to CLDR ${PINNED_CLDR}. Run the script with a Node.js release that bundles it.`,
  );
  process.exit(2);
}

const check = process.argv.includes('--check');

// --- The regions: every region of the catalogue, in ordinal order ---
const regions = [...new Set(
  [...readFileSync(CULTURE_DATA, 'utf8').matchAll(/^\[[a-z]+-([A-Z]{2})\]$/gmu)].map((match) => match[1]),
)].sort();

if (regions.length === 0) {
  console.error(`No language and region pair was found in ${CULTURE_DATA}.`);
  process.exit(2);
}

// --- Every shipped language's resources: the neutral English file and each satellite ---
let stale = 0;
for (const file of readdirSync(RESOURCES).filter((name) => /^Strings(\.[a-z]{2,3})?\.resx$/u.test(name)).sort()) {
  const language = /^Strings\.([a-z]{2,3})\.resx$/u.exec(file)?.[1] ?? 'en';
  const names = new Intl.DisplayNames([language], { type: 'region', fallback: 'code' });

  // The block, one entry per region, its value escaped for XML.
  const entries = regions.map((region) => {
    const name = names.of(region).replace(BIDI_CONTROLS, '');
    return `  <data name="Region_${region}" xml:space="preserve">\n    <value>${escapeXml(name)}</value>\n  </data>\n`;
  });
  const block = BLOCK_START + entries.join('') + BLOCK_END;

  // The file without its previous names, and the new block before the closing tag.
  const path = join(RESOURCES, file);
  const original = readFileSync(path, 'utf8');
  const stripped = original.replace(BLOCK_PATTERN, '').replace(ENTRY_PATTERN, '');
  const closing = stripped.lastIndexOf('</root>');
  if (closing < 0) {
    console.error(`${path} has no closing </root> tag.`);
    process.exit(2);
  }

  const updated = stripped.slice(0, closing) + block + stripped.slice(closing);
  if (updated === original) {
    continue;
  }

  if (check) {
    console.error(`${path} differs from the generated region names.`);
    stale++;
  } else {
    writeFileSync(path, updated, 'utf8');
    console.log(`Wrote ${regions.length} region names to ${path}.`);
  }
}

process.exit(stale > 0 ? 1 : 0);

/**
 * Escapes the characters XML text may not hold as they are.
 * @param {string} text The text.
 * @returns {string} The escaped text.
 */
function escapeXml(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}
