using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Metadata.Conventions;
using Tellma.Core.Abstractions.Entities;
using Tellma.Core.Composition;

namespace Tellma.Core.Data.Conventions
{
    /// <summary>
    ///     Gives every keyed table but a sibling its sequence, <c>&lt;schema&gt;.sq_&lt;Table&gt;</c>,
    ///     <c>AS int</c> or <c>AS bigint</c> like the key, <c>START WITH 1000 INCREMENT BY 1 NO CYCLE</c>.
    ///     The ids 1 to 999 are reserved for well-known seeded rows.
    /// </summary>
    /// <remarks>
    ///     The key of every keyed table, a sibling's included, is never generated by the database: no
    ///     table has an <c>IDENTITY</c> column, and the allocator reserves ranges of the sequence
    ///     instead. A key of any type but <see cref="int" /> or <see cref="long" /> fails the model.
    /// </remarks>
    internal sealed class SequenceConvention : IModelFinalizingConvention
    {
        /// <summary>The first value every sequence returns.</summary>
        public const long StartValue = 1000;

        /// <inheritdoc />
        public void ProcessModelFinalizing(IConventionModelBuilder modelBuilder, IConventionContext<IConventionModelBuilder> context)
        {
            foreach (IConventionEntityType entityType in ConventionModel.Tables(modelBuilder.Metadata))
            {
                Type? keyType = EntityShapes.KeyTypeOf(entityType.ClrType);
                if (keyType is null)
                {
                    continue;
                }

                if (keyType != typeof(int) && keyType != typeof(long))
                {
                    throw new InvalidOperationException(
                        $"The entity {TypeDisplay.Qualified(entityType.ClrType)} has a key of type {keyType.Name}; an entity's key is an int or a long.");
                }

                // --- No database-generated key, sibling or not ---
                IConventionProperty id = entityType.FindProperty(nameof(Entity<>.Id))!;
                _ = id.Builder.ValueGenerated(ValueGenerated.Never, fromDataAnnotation: true);

                if (SiblingConvention.IsSibling(entityType))
                {
                    continue;
                }

                // --- The table's own sequence ---
                IConventionSequenceBuilder sequence = modelBuilder.HasSequence(
                    ConstraintNames.Sequence(ConventionModel.Table(entityType)), entityType.GetSchema(), fromDataAnnotation: true);
                _ = sequence.HasType(keyType, fromDataAnnotation: true);
                _ = sequence.StartsAt(StartValue, fromDataAnnotation: true);
                _ = sequence.IncrementsBy(1, fromDataAnnotation: true);
                _ = sequence.IsCyclic(false, fromDataAnnotation: true);
            }
        }
    }
}
