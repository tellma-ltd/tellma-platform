using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Tellma.Core.Abstractions.Caching;
using Tellma.Core.Abstractions.Data;

namespace Tellma.Core.Caching
{
    /// <summary>
    ///     A row of <c>core.VersionTags</c>: one tenant-level version tag, such as <c>settings</c>,
    ///     <c>permissions</c>, <c>entities</c>, <c>entity:&lt;Name&gt;</c> or a pack's name.
    /// </summary>
    /// <remarks>
    ///     Not an entity: no surrogate key, no history, no audit columns, no table type; absent from the
    ///     query language and from every stack. Only the migrator inserts rows, one per name the
    ///     registry knows; batches only ever update them.
    /// </remarks>
    internal sealed class VersionTagRow
    {
        /// <summary>The tag's name, the key, <c>nvarchar(128)</c>.</summary>
        public string Name { get; set; } = null!;

        /// <summary>The tag's current value, generated by the application on every bump.</summary>
        public Guid Tag { get; set; }
    }

    /// <summary>The model of <c>core.VersionTags</c>, with no seed row: the migrator seeds it.</summary>
    internal sealed class VersionTagRowConfiguration : IEntityTypeConfiguration<VersionTagRow>
    {
        /// <summary>The table.</summary>
        public static readonly TableName Table = new("core", "VersionTags");

        /// <inheritdoc />
        public void Configure(EntityTypeBuilder<VersionTagRow> builder)
        {
            ArgumentNullException.ThrowIfNull(builder);

            // --- The table: keyed by name, clustered; the guard seeks it, the prelude scans its one page ---
            _ = builder.ToTable(Table.Name, Table.Schema);
            _ = builder.HasKey(static row => row.Name);
            _ = builder.Property(static row => row.Name).HasMaxLength(VersionTagNames.MaxNameLength).ValueGeneratedNever();

            // --- A fresh tag for every seeded row; the convention names the default DF_VersionTags_Tag ---
            _ = builder.Property(static row => row.Tag).HasDefaultValueSql("NEWID()");
        }
    }
}
