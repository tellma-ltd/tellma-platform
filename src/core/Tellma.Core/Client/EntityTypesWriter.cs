using System.Globalization;
using System.Text;
using Tellma.Core.Abstractions.Client;
using Tellma.Core.Localization;

namespace Tellma.Core.Client
{
    // The file is spec 0029 §15's: one wire interface and one path shape per entity, registered by
    // name in @tellma/core's two registries, so a declaration type-checks with no type argument.
    /// <summary>
    ///     Writes the TypeScript declarations of the client entity model: a literal union per C#
    ///     enum, a wire interface per entity, and the augmentation of <c>@tellma/core</c>'s entity
    ///     registries.
    /// </summary>
    /// <remarks>
    ///     The text is a pure function of the model, with <c>\n</c> line endings on every operating
    ///     system, so one composition always writes the same bytes.
    /// </remarks>
    internal static class EntityTypesWriter
    {
        /// <summary>The generated file's name in the client project's generated folder.</summary>
        public const string FileName = "tellma-entities.d.ts";

        /// <summary>The package whose registries the file augments and whose value types it imports.</summary>
        private const string CorePackage = "@tellma/core";

        /// <summary>The type of a decimal or a long, which travels as decimal text.</summary>
        private const string DecimalType = "TmDecimal";

        /// <summary>The type of a JSON value.</summary>
        private const string JsonType = "TmJson";

        /// <summary>One level of indentation.</summary>
        private const string Indent = "  ";

        /// <summary>Writes the declarations.</summary>
        /// <param name="entities">The entities, in the order to write them.</param>
        /// <param name="enums">The C# enums' descriptions, which become literal unions; a value set's values are known only as text.</param>
        /// <returns>The file's text.</returns>
        /// <exception cref="InvalidOperationException">Two declarations would have one TypeScript name.</exception>
        public static string Write(IReadOnlyList<ClientEntityMetadata> entities, IReadOnlyList<ClientEnumMetadata> enums)
        {
            ArgumentNullException.ThrowIfNull(entities);
            ArgumentNullException.ThrowIfNull(enums);

            // --- The TypeScript names, each declared once ---
            Dictionary<string, string> enumTypes = new(StringComparer.Ordinal);
            Dictionary<string, string> declared = new(StringComparer.Ordinal);
            foreach (ClientEnumMetadata item in enums)
            {
                enumTypes[item.Name] = Claim(declared, TypeName(item.Name), $"the enum {item.Name}");
            }

            Dictionary<string, string> entityTypes = new(StringComparer.Ordinal);
            foreach (ClientEntityMetadata entity in entities)
            {
                entityTypes[entity.Name] = Claim(declared, TypeName(entity.Name), $"the entity {entity.Name}");
            }

            // --- The bodies first, so the import names only the value types they use ---
            StringBuilder body = new();
            HashSet<string> imports = new(StringComparer.Ordinal);
            foreach (ClientEnumMetadata item in enums)
            {
                WriteEnum(body, item, enumTypes[item.Name]);
            }

            foreach (ClientEntityMetadata entity in entities)
            {
                WriteInterface(body, entity, entityTypes, enumTypes, imports);
            }

            WriteRegistries(body, entities, entityTypes);

            // --- The header and the import, then the bodies ---
            StringBuilder file = new();
            _ = file.Append("// <auto-generated>\n")
                .Append("// The typed entity model of this distribution, written by the client metadata\n")
                .Append("// emit from the server's composition. Never edit it: every build rewrites it.\n")
                .Append("// </auto-generated>\n\n");
            if (imports.Count > 0)
            {
                _ = file.Append("import type { ").Append(string.Join(", ", imports.Order(StringComparer.Ordinal))).Append(" } from '").Append(CorePackage).Append("';\n\n");
            }

            return file.Append(body).ToString();
        }

        /// <summary>A qualified name's TypeScript name: its schema capitalized, then its last segment (<c>gl.Center</c> is <c>GlCenter</c>).</summary>
        /// <param name="name">The qualified name.</param>
        /// <returns>The TypeScript name.</returns>
        public static string TypeName(string name)
        {
            ArgumentNullException.ThrowIfNull(name);
            return StringKeyConventions.SchemaPrefix(name) + StringKeyConventions.LastSegment(name);
        }

        /// <summary>Records a TypeScript name, refusing one already taken.</summary>
        /// <param name="declared">The names taken so far, with what took each.</param>
        /// <param name="name">The name.</param>
        /// <param name="owner">What declares it, for the refusal.</param>
        /// <returns>The name.</returns>
        /// <exception cref="InvalidOperationException">The name is taken.</exception>
        private static string Claim(Dictionary<string, string> declared, string name, string owner)
        {
            return declared.TryAdd(name, owner)
                ? name
                : throw new InvalidOperationException(
                    $"The TypeScript declarations of {declared[name]} and of {owner} would both be named {name}; rename one so the names differ by more than their schema's dot.");
        }

        /// <summary>Writes a C# enum's literal union.</summary>
        /// <param name="file">The file so far.</param>
        /// <param name="item">The enum.</param>
        /// <param name="typeName">Its TypeScript name.</param>
        private static void WriteEnum(StringBuilder file, ClientEnumMetadata item, string typeName)
        {
            _ = file.Append("/** The values of the enum `").Append(item.Name).Append("`, as the wire spells them. */\n")
                .Append("export type ").Append(typeName).Append(" = ")
                .Append(item.Values.Count == 0 ? "never" : string.Join(" | ", item.Values.Select(static value => Literal(value.Value))))
                .Append(";\n\n");
        }

        /// <summary>
        ///     Writes an entity's wire interface: its properties and child collections by their wire
        ///     names, a nullable member, a twin or a collection optional.
        /// </summary>
        /// <param name="file">The file so far.</param>
        /// <param name="entity">The entity.</param>
        /// <param name="entityTypes">The entities' TypeScript names, by entity name.</param>
        /// <param name="enumTypes">The C# enums' TypeScript names, by enum name.</param>
        /// <param name="imports">Receives the value types the interface uses.</param>
        private static void WriteInterface(
            StringBuilder file,
            ClientEntityMetadata entity,
            Dictionary<string, string> entityTypes,
            Dictionary<string, string> enumTypes,
            HashSet<string> imports)
        {
            _ = file.Append("/** A row of the entity `").Append(entity.Name).Append("`, as the wire carries it. */\n")
                .Append("export interface ").Append(entityTypes[entity.Name]).Append(" {\n");

            // --- The properties: a nullable value or a twin may be absent ---
            foreach (ClientPropertyMetadata property in entity.Properties)
            {
                string type = PropertyType(entity, property, enumTypes, imports);
                bool optional = property.Nullable || property.Multilingual is { Slot: > 1 };
                _ = file.Append(Indent).Append("/** The property `").Append(property.Name).Append("`. */\n")
                    .Append(Indent).Append(Member(property.Json)).Append(optional ? "?: " : ": ").Append(type).Append(optional ? " | null" : string.Empty).Append(";\n");
            }

            // --- The child collections, which a payload may leave out ---
            foreach (ClientChildMetadata child in entity.Children)
            {
                string type = entityTypes.TryGetValue(child.Entity, out string? childType) ? $"{childType}[]" : $"{JsonType}[]";
                if (childType is null)
                {
                    _ = imports.Add(JsonType);
                }

                _ = file.Append(Indent).Append("/** The child collection `").Append(child.Name).Append("`. */\n")
                    .Append(Indent).Append(Member(child.Json)).Append("?: ").Append(type).Append(" | null;\n");
            }

            _ = file.Append("}\n\n");
        }

        /// <summary>A property's TypeScript type.</summary>
        /// <param name="entity">The entity.</param>
        /// <param name="property">The property.</param>
        /// <param name="enumTypes">The C# enums' TypeScript names, by enum name.</param>
        /// <param name="imports">Receives the value types the type uses.</param>
        /// <returns>The type.</returns>
        private static string PropertyType(ClientEntityMetadata entity, ClientPropertyMetadata property, Dictionary<string, string> enumTypes, HashSet<string> imports)
        {
            // A long key, a long and a decimal are decimal text; a C# enum its literals; a value set plain text.
            bool isLongKey = property.Name == entity.Key.Property && entity.Key.Type == ClientKeyType.Long;
            string type = property.Type switch
            {
                ClientDataType.Decimal => DecimalType,
                ClientDataType.Integer when property.Long || isLongKey => DecimalType,
                ClientDataType.Json => JsonType,
                ClientDataType.Integer or ClientDataType.Float => "number",
                ClientDataType.Bool => "boolean",
                ClientDataType.Enum when property.Enum is string name && enumTypes.TryGetValue(name, out string? enumType) => enumType,
                ClientDataType.String or ClientDataType.Enum or ClientDataType.Date or ClientDataType.DateTime or ClientDataType.Instant
                    or ClientDataType.Time or ClientDataType.Guid or ClientDataType.Binary => "string",
                _ => throw new InvalidOperationException($"The property {property.Name} of {entity.Name} has a data type the declarations do not know."),
            };

            if (type is DecimalType or JsonType)
            {
                _ = imports.Add(type);
            }

            return type;
        }

        /// <summary>
        ///     Writes the augmentation of <c>@tellma/core</c>'s registries: each entity's wire
        ///     interface, and its path shape, the names a path may step through.
        /// </summary>
        /// <param name="file">The file so far.</param>
        /// <param name="entities">The entities.</param>
        /// <param name="entityTypes">The entities' TypeScript names, by entity name.</param>
        private static void WriteRegistries(StringBuilder file, IReadOnlyList<ClientEntityMetadata> entities, Dictionary<string, string> entityTypes)
        {
            _ = file.Append("declare module '").Append(CorePackage).Append("' {\n");

            // --- The wire interfaces, by entity name ---
            _ = file.Append(Indent).Append("/** The wire interface of every entity of this distribution, by entity name. */\n")
                .Append(Indent).Append("interface TmEntityTypes {\n");
            foreach (ClientEntityMetadata entity in entities)
            {
                _ = file.Append(Indent).Append(Indent).Append("/** The entity `").Append(entity.Name).Append("`. */\n")
                    .Append(Indent).Append(Indent).Append(Literal(entity.Name)).Append(": ").Append(entityTypes[entity.Name]).Append(";\n");
            }

            _ = file.Append(Indent).Append("}\n\n");

            // --- The path shapes: the queryable scalars, the multilingual groups, the navigations and the collections ---
            _ = file.Append(Indent).Append("/** The path shape of every entity of this distribution, by entity name. */\n")
                .Append(Indent).Append("interface TmEntityShapes {\n");
            string inner = Indent + Indent + Indent;
            foreach (ClientEntityMetadata entity in entities)
            {
                string[] scalars = [.. entity.Properties.Where(static property => property.Queryable).Select(static property => Literal(property.Name))];
                string[] groups = [.. entity.Properties.Select(static property => property.Multilingual?.Group).OfType<string>().Distinct(StringComparer.Ordinal).Select(Literal)];
                _ = file.Append(Indent).Append(Indent).Append("/** The path shape of the entity `").Append(entity.Name).Append("`. */\n")
                    .Append(Indent).Append(Indent).Append(Literal(entity.Name)).Append(": {\n")
                    .Append(inner).Append("scalars: ").Append(Union(scalars)).Append(";\n")
                    .Append(inner).Append("groups: ").Append(Union(groups)).Append(";\n")
                    .Append(inner).Append("navigations: ").Append(Map(entity.Navigations.Select(static navigation => (navigation.Name, navigation.Target)))).Append(";\n")
                    .Append(inner).Append("children: ").Append(Map(entity.Children.Select(static child => (child.Name, child.Entity)))).Append(";\n")
                    .Append(Indent).Append(Indent).Append("};\n");
            }

            _ = file.Append(Indent).Append("}\n}\n");
        }

        /// <summary>A union of literal types, or <c>never</c> for none.</summary>
        /// <param name="literals">The literals.</param>
        /// <returns>The type.</returns>
        private static string Union(string[] literals)
        {
            return literals.Length == 0 ? "never" : string.Join(" | ", literals);
        }

        /// <summary>An object type of member names to entity names: <c>{ Parent: 'gl.Center' }</c>.</summary>
        /// <param name="members">The members and the entities they reach.</param>
        /// <returns>The type.</returns>
        private static string Map(IEnumerable<(string Name, string Target)> members)
        {
            string[] entries = [.. members.Select(static member => $"{Member(member.Name)}: {Literal(member.Target)}")];
            return entries.Length == 0 ? "{}" : $"{{ {string.Join("; ", entries)} }}";
        }

        /// <summary>A member name, quoted when it is no plain identifier.</summary>
        /// <param name="name">The name.</param>
        /// <returns>The member name as TypeScript writes it.</returns>
        private static string Member(string name)
        {
            bool identifier = name.Length > 0
                && (char.IsAsciiLetter(name[0]) || name[0] is '_' or '$')
                && name.All(static c => char.IsAsciiLetterOrDigit(c) || c is '_' or '$');
            return identifier ? name : Literal(name);
        }

        /// <summary>A string literal in single quotes, its backslashes, quotes and control characters escaped.</summary>
        /// <param name="value">The text.</param>
        /// <returns>The literal.</returns>
        private static string Literal(string value)
        {
            StringBuilder literal = new("'");
            foreach (char c in value)
            {
                _ = c switch
                {
                    '\\' => literal.Append("\\\\"),
                    '\'' => literal.Append("\\'"),
                    _ when char.IsControl(c) || c is '\u2028' or '\u2029' => literal.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture)),
                    _ => literal.Append(c),
                };
            }

            return literal.Append('\'').ToString();
        }
    }
}
